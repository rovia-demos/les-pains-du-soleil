window.LPDS_I18N = (function () {
  const LANGS = ['fr', 'en', 'es'];
  const fr = {};
  const metaDesc = document.querySelector('meta[name="description"]');

  // Mémorise le français d'origine pour pouvoir y revenir
  document.querySelectorAll('[data-i18n]').forEach((el) => { fr[el.dataset.i18n] = el.innerHTML; });
  document.querySelectorAll('[data-i18n-attr]').forEach((el) => {
    el.dataset.i18nAttr.split(',').forEach((pair) => {
      const [attr, key] = pair.split(':');
      fr[key + '@' + attr] = el.getAttribute(attr);
    });
  });
  fr['meta.title'] = document.title;
  fr['meta.desc'] = metaDesc ? metaDesc.content : '';

  function dict(lang) { return lang === 'fr' ? fr : window.I18N[lang]; }

  function apply(lang) {
    if (!LANGS.includes(lang)) lang = 'fr';
    const d = dict(lang);
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const v = d[el.dataset.i18n];
      if (v == null) return;
      if (v.includes('<')) el.innerHTML = v; else el.textContent = v.replace(/&amp;/g, '&');
    });
    document.querySelectorAll('[data-i18n-attr]').forEach((el) => {
      el.dataset.i18nAttr.split(',').forEach((pair) => {
        const [attr, key] = pair.split(':');
        const v = d[key + '@' + attr] ?? d[key];
        if (v != null) el.setAttribute(attr, v.replace(/<[^>]+>/g, ''));
      });
    });
    document.documentElement.lang = lang;
    document.title = d['meta.title'];
    if (metaDesc) metaDesc.content = d['meta.desc'];
    document.querySelectorAll('[data-lang]').forEach((b) => b.setAttribute('aria-pressed', String(b.dataset.lang === lang)));
    try { localStorage.setItem('lpds-lang', lang); } catch (e) { /* stockage indisponible : sans conséquence */ }
    const url = new URL(location.href);
    if (lang === 'fr') url.searchParams.delete('lang'); else url.searchParams.set('lang', lang);
    history.replaceState(null, '', url);
    document.dispatchEvent(new CustomEvent('langchange', { detail: lang }));
  }

  function initial() {
    const q = new URLSearchParams(location.search).get('lang');
    if (LANGS.includes(q)) return q;
    try { const s = localStorage.getItem('lpds-lang'); if (LANGS.includes(s)) return s; } catch (e) { /* idem */ }
    const nav = (navigator.language || 'fr').slice(0, 2);
    return LANGS.includes(nav) ? nav : 'fr';
  }

  document.addEventListener('click', (e) => {
    const b = e.target.closest('[data-lang]');
    if (b) apply(b.dataset.lang);
  });

  return { apply, initial };
})();
